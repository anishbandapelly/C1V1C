"""Amazon Bedrock narrator: rephrases a deterministic explanation; never invents numbers.

Uses the Converse API with the configured model or inference-profile id. A response is accepted only
if every number it contains matches a value in the deterministic explanation.
"""
from __future__ import annotations

import json

from c1v1c.config import Settings
from c1v1c.explainer import numbers_supported
from c1v1c.schemas import DecisionExplanation

SYSTEM = (
    "You explain the output of an urban-sustainability optimisation model to city planners in plain English. "
    "Use ONLY the facts in the JSON you are given. Do not add numbers, costs, places, sources or claims that are not in it. "
    "Copy numbers exactly as given. Say clearly that results are modelled screening estimates based on declared assumptions. "
    "Write 120-180 words, no headings, no bullet points."
)


class BedrockUnavailable(RuntimeError):
    pass


def _client(settings: Settings):
    import boto3
    from botocore.config import Config

    cfg = Config(region_name=settings.aws_region, connect_timeout=settings.aws_timeout_s,
                 read_timeout=max(20.0, settings.aws_timeout_s), retries={"max_attempts": 2, "mode": "standard"})
    return boto3.client("bedrock-runtime", config=cfg)


def facts(e: DecisionExplanation) -> dict:
    return {"headline": e.headline, "why_selected": e.why_selected[:6], "improved": e.improved, "worsened": e.worsened,
            "underserved": e.underserved, "binding_constraints": e.binding_constraints, "shock_findings": e.shock_findings,
            "unintended_consequences": e.unintended_consequences[:4], "key_uncertainties": e.uncertainties[:4]}


def narrate(e: DecisionExplanation, settings: Settings | None = None, client=None) -> DecisionExplanation:
    """Return the explanation with a Bedrock narrative if (and only if) it validates; otherwise unchanged plus status."""
    settings = settings or Settings.load()
    if client is None and settings.offline_mode:
        return e.model_copy(update={"bedrock_status": "offline mode: deterministic explanation shown"})
    if not settings.bedrock_model_id:
        return e.model_copy(update={"bedrock_status": "BEDROCK_MODEL_ID not configured: deterministic explanation shown"})
    try:
        text = invoke(json.dumps(facts(e), indent=1), settings, client)
    except BedrockUnavailable as exc:
        return e.model_copy(update={"bedrock_status": f"Bedrock unavailable ({exc}); deterministic explanation shown"})
    if not text.strip():
        return e.model_copy(update={"bedrock_status": "Bedrock returned empty text; deterministic explanation shown"})
    ok, bad = numbers_supported(text, e)
    if not ok:
        return e.model_copy(update={"bedrock_status": f"Bedrock response rejected (unsupported numbers {bad[:5]}); "
                                                      "deterministic explanation shown"})
    return e.model_copy(update={"narrative": text.strip(), "explanation_source": "bedrock",
                                "bedrock_status": f"generated by {settings.bedrock_model_id}; all numbers validated",
                                "validation_passed": True})


def invoke(prompt: str, settings: Settings, client=None) -> str:
    from botocore.exceptions import BotoCoreError, ClientError

    client = client or _client(settings)
    try:
        r = client.converse(modelId=settings.bedrock_model_id, system=[{"text": SYSTEM}],
                            messages=[{"role": "user", "content": [{"text": "Facts (JSON):\n" + prompt}]}],
                            inferenceConfig={"maxTokens": 400, "temperature": 0.1})
    except ClientError as exc:
        raise BedrockUnavailable(exc.response.get("Error", {}).get("Code", "ClientError")) from None
    except BotoCoreError as exc:
        raise BedrockUnavailable(exc.__class__.__name__) from None
    try:
        return "".join(part.get("text", "") for part in r["output"]["message"]["content"])
    except (KeyError, TypeError):
        raise BedrockUnavailable("malformed response") from None
